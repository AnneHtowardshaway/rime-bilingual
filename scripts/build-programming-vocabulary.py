#!/usr/bin/env python3
"""生成万象的编程、AI、日常与设备精确匹配词表（仅维护时运行）。"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
RIME = ROOT / "rime"
OUTPUT = RIME / "data/programming-english.tsv"
LABELS = {
    "tech_english_computer": "计算机 · 专业英语",
    "tech_english_go": "Go · 库与 API",
    "tech_english_rust": "Rust · 库与 API",
    "tech_english_python": "Python · 库与 API",
    "tech_english_java": "Java · 库与 API",
    "tech_english_javascript": "JS · 库与 API",
    "tech_english_typescript": "TS · 类型与工具",
    "daily_english": "日常英语",
    "ai_english": "AI · 工具与术语",
    "langchain_agent": "Agent · 框架与术语",
    "electronics_english": "设备 · 产品名称",
}
SUPPLEMENTS = ("daily_english", "ai_english", "langchain_agent", "electronics_english")
SHORT_CODES = {"go", "js", "ts"}
DAILY_SHORT_CODES = {"hi", "ok", "no", "jd"}


def collect(name, seen, words):
    if name in seen:
        raise ValueError(f"循环或重复导入: {name}")
    if not re.fullmatch(r"[a-z_]+", name):
        raise ValueError(f"非法公开词库名称: {name}")
    seen.add(name)
    path = RIME / f"{name}.dict.yaml"
    header, body = path.read_text(encoding="utf-8").split("\n...\n", 1)
    for number, row in enumerate(body.splitlines(), 1):
        if not row.strip() or row.startswith("#"):
            continue
        fields = row.split("\t")
        if len(fields) != 3 or not fields[0] or not fields[1]:
            raise ValueError(f"词条格式错误: {path.name}, body line {number}")
        text, code, weight = fields
        # 数字键用于选词；短编码只开放明确的语言缩写与已有日常词。
        if (not re.fullmatch(r"[a-z]{3,}", code) and code not in SHORT_CODES
                and not (name == "daily_english" and code in DAILY_SHORT_CODES)):
            continue
        if text.strip() != text or not text.isprintable():
            raise ValueError(f"英文词条含非法字符: {path.name}: {text!r}")
        priority = int(weight)
        # 同码沿用码表权重。相同权重保留先出现的词，不依赖集合遍历顺序。
        if code not in words or priority > words[code][0]:
            words[code] = (priority, text, LABELS.get(name, "编程 · 技术英文"))
    imports = re.search(r"(?m)^import_tables:\n((?:[ \t]+-[^\n]*\n?)*)", header)
    if imports:
        for row in imports[1].splitlines():
            child = row.split("-", 1)[1].split("#", 1)[0].strip()
            collect(child, seen, words)
    seen.remove(name)


def render():
    words = {}
    collect("tech_english_table", set(), words)
    # 保持已有编程编码的规范输出；新增同码优先日常词，避免 book → MacBook。
    for name in SUPPLEMENTS:
        additions = {}
        collect(name, set(), additions)
        for code, word in additions.items():
            words.setdefault(code, word)
    internet = {
        row.split("\t", 1)[0]
        for row in (RIME / "data/internet-english.tsv").read_text(encoding="utf-8").splitlines()
        if row and not row.startswith("#")
    }
    rows = ["# SPDX-License-Identifier: GPL-3.0-or-later",
            "# Generated by scripts/build-programming-vocabulary.py; edit rime/*.dict.yaml instead."]
    for code, (_, text, label) in sorted(words.items()):
        if code not in internet:
            rows.append(f"{code}\t{text}\t{label}")
    return "\n".join(rows) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("编程词表未同步，请运行 python3 scripts/build-programming-vocabulary.py")
    else:
        OUTPUT.write_text(text, encoding="utf-8")
    print(f"编程与主题英文词表{'校验' if args.check else '生成'}通过：{len(text.splitlines()) - 2} 个编码")


if __name__ == "__main__":
    main()
